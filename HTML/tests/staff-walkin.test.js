const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const BookingTime = require('../Shared/booking-time');
const source = fs.readFileSync(require.resolve('../Staff/staff.js'), 'utf8');
test('walk-in selection filters dentists, uses live availability and saves service prices and assignment', async () => {
  const boxes = [{ value: '0', checked: false }, { value: '1', checked: false }];
  const nodes = {};
  const qs = selector => nodes[selector] ||= { value: '', innerHTML: '', querySelectorAll: () => boxes, reportValidity: () => true };
  const clinic = { services: [{ id:'c', name: 'Consultation', price: 500 }, { id:'r', name: 'Root Canal Treatment', price: 1000 }], dentists: [{ id: 'all', name: 'Imelda', specialty: 'All Services' }, { id: 'general', name: 'General', specialty: 'General Dentist' }], appointments: [] };
  const state = { appointments: [] };
  let requested, posted;
  const unavailable = new Set();
  const context = { crypto: {randomUUID:()=> '00000000-0000-4000-8000-000000000001'}, GmDentalApiFetch:async(url,options)=>{posted=JSON.parse(options.body);return {ok:true,json:async()=>({})};}, withSyncSuspended:fn=>fn(), pullFromClinicDb:()=>{}, window: { GMDefaultAccounts: { normalizeDb: db => db }, GmDentalSupabaseSync: { pull: async () => true } }, qs, getClinicDb: () => clinic, todayISO: () => '2026-10-07', openSharedModal: () => {}, escapeHtml: String, escapeAttr: String, GMDentistServices: { canPerform: (d, name) => d.id === 'all' || name === 'Consultation' }, StaffAvailability: { slots: (...args) => { requested = args; return unavailable.has(args[1][0].id) ? [] : ['10:00']; } }, GMClinicHours: { allows: () => true }, BookingTime, formatTime: () => '10:00 AM', state, uid: () => 'new', saveState: () => {}, closeSharedModal: () => {}, renderAll: () => {}, addNotification: () => {}, showToast: () => {} };
  vm.runInNewContext(source.slice(source.indexOf('function openWalkInModal()'), source.indexOf('function bindStaffAppointmentCalendar')), context);
  context.openWalkInModal();
  for (const [id, value, expected] of [['walkInPatient','Ana123 Cruz!','Ana Cruz'],['walkInAge','2e5','25'],['walkInContact','09ab123456789','09123456789']]) {
    qs('#'+id).value=value; qs('#'+id).oninput({isComposing:false});
    assert.equal(qs('#'+id).value,expected);
  }
  boxes[0].checked = true; boxes[0].onchange();
  assert.match(qs('#walkInDentist').innerHTML, /General/);
  unavailable.add('general'); boxes[0].onchange();
  assert.doesNotMatch(qs('#walkInDentist').innerHTML, />General</, 'qualified dentist without remaining slots is excluded');
  unavailable.add('all'); boxes[0].onchange();
  assert.equal(qs('#walkInDentist').disabled, true);
  assert.match(qs('#walkInDentist').innerHTML, /No qualified dentists available today/);
  unavailable.clear();
  boxes[1].checked = true; boxes[1].onchange();
  assert.doesNotMatch(qs('#walkInDentist').innerHTML, />General</);
  qs('#walkInDentist').value = 'all'; qs('#walkInDentist').onchange();
  assert.match(qs('#walkInTime').innerHTML, /10:00 AM/);
  assert.equal(requested[3].services.length, 2);
  qs('#walkInPatient').value = 'Walk-in'; qs('#walkInTime').value = '10:00';
  await qs('#saveWalkInBtn').onclick();
  assert.equal(posted.patient.name, 'Walk-in');
  assert.equal(posted.appointment.dentistId, 'all');
  assert.equal(posted.appointment.services.length, 2);
  assert.equal(state.appointments.length, 0, 'no optimistic orphan appointment');
  const original=posted;
  qs('#walkInTime').value = '09:00';
  await qs('#saveWalkInBtn').onclick();
  assert.equal(posted,original,'unavailable start is rejected before sending');
});
