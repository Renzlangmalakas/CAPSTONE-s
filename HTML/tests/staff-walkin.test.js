const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const BookingTime = require('../Shared/booking-time');
const source = fs.readFileSync(require.resolve('../Staff/staff.js'), 'utf8');
test('walk-in selection filters dentists, uses live availability and saves service prices and assignment', async () => {
  const boxes = [{ value: '0', checked: false }, { value: '1', checked: false }];
  const nodes = {};
  const qs = selector => nodes[selector] ||= { value: '', innerHTML: '', querySelectorAll: () => boxes };
  const clinic = { services: [{ name: 'Consultation', price: 500 }, { name: 'Root Canal Treatment', price: 1000 }], dentists: [{ id: 'all', name: 'Imelda', specialty: 'All Services' }, { id: 'general', name: 'General', specialty: 'General Dentist' }], appointments: [] };
  const state = { appointments: [] };
  let requested, arrived;
  const context = { markPatientArrived: async id => { arrived = id; return true; }, window: { GMDefaultAccounts: { normalizeDb: db => db }, GmDentalSupabaseSync: { flushNow: async () => true } }, qs, getClinicDb: () => clinic, todayISO: () => '2026-10-07', openSharedModal: () => {}, escapeHtml: String, escapeAttr: String, GMDentistServices: { canPerform: (d, name) => d.id === 'all' || name === 'Consultation' }, StaffAvailability: { slots: (...args) => { requested = args; return ['10:00']; } }, GMClinicHours: { allows: () => true }, BookingTime, formatTime: () => '10:00 AM', state, uid: () => 'new', saveState: () => {}, closeSharedModal: () => {}, renderAll: () => {}, addNotification: () => {}, showToast: () => {} };
  vm.runInNewContext(source.slice(source.indexOf('function openWalkInModal()'), source.indexOf('function bindStaffAppointmentCalendar')), context);
  context.openWalkInModal();
  boxes[0].checked = true; boxes[0].onchange();
  assert.match(qs('#walkInDentist').innerHTML, /General/);
  boxes[1].checked = true; boxes[1].onchange();
  assert.doesNotMatch(qs('#walkInDentist').innerHTML, />General</);
  qs('#walkInDentist').value = 'all'; qs('#walkInDentist').onchange();
  assert.match(qs('#walkInTime').innerHTML, /10:00 AM/);
  assert.equal(requested[3].services.length, 2);
  qs('#walkInPatient').value = 'Walk-in'; qs('#walkInTime').value = '10:00';
  await qs('#saveWalkInBtn').onclick();
  assert.equal(arrived, 'new');
  assert.equal(state.appointments.length, 1);
  assert.equal(state.appointments[0].total, 1500);
  assert.equal(state.appointments[0].dentistId, 'all');
  assert.equal(state.appointments[0].services.length, 2);
  qs('#walkInTime').value = '09:00';
  await qs('#saveWalkInBtn').onclick();
  assert.equal(arrived, 'new');
  assert.equal(state.appointments.length, 1, 'unavailable start is rejected');
});
